import { z } from 'zod';
import { ActionSchema, PlayerIdSchema, PlayerNameSchema, type Action } from './actions.js';
import type { ErrorCode } from './errors.js';
import type { GameEvent } from './events.js';
import { RANKS, type Rank } from './cards.js';
import type { PlayerId, TurnStep } from './game.js';
import { PROTOCOL_LIMITS } from './limits.js';
import type { GameView } from './view.js';

// Network protocol between the web client and the server (Socket.IO).
// Documented in docs/PROTOCOLO.md. Every client -> server payload has a Zod
// schema here; the server validates with these schemas (and then with the
// game engine) and never trusts anything else the client sends. The client can
// reuse the same schemas to validate forms before sending.

export const PROTOCOL_VERSION = 1;

// --- room codes and session tokens ---------------------------------------------

/** Characters used in room codes: digits and capitals without the look-alikes 0/O, 1/I/L. */
export const ROOM_CODE_ALPHABET = '23456789ABCDEFGHJKMNPQRSTUVWXYZ';

export const ROOM_CODE_LIMITS = { minLength: 4, maxLength: 12 } as const;

const ROOM_CODE_PATTERN = new RegExp(
  `^[${ROOM_CODE_ALPHABET}]{${ROOM_CODE_LIMITS.minLength},${ROOM_CODE_LIMITS.maxLength}}$`,
);

/** A room code typed by a person: surrounding spaces and lower case are accepted. */
export const RoomCodeSchema = z
  .string()
  .max(ROOM_CODE_LIMITS.maxLength + 8)
  .trim()
  .toUpperCase()
  .regex(ROOM_CODE_PATTERN);

/** Session tokens are 32 random bytes in base64url (43 characters), generated by the server. */
export const SESSION_TOKEN_PATTERN = /^[A-Za-z0-9_-]{43}$/;
export const SessionTokenSchema = z.string().regex(SESSION_TOKEN_PATTERN);

// --- player names ----------------------------------------------------------------

// Control and format characters (zero-width, bidirectional overrides), line and
// paragraph separators, private-use and unassigned code points.
const INVISIBLE_CHARS = /[\p{Cc}\p{Cf}\p{Co}\p{Cn}\p{Zl}\p{Zp}]/gu;
// More than two combining marks in a row ("zalgo" text).
const MARK_FLOOD = /(\p{M}{2})\p{M}+/gu;

/**
 * Normalizes a display name: Unicode NFKC, no invisible or control characters,
 * at most two stacked combining marks, single spaces, trimmed. It does not
 * escape HTML: names are plain text and the client must render them as text.
 */
export function sanitizePlayerName(raw: string): string {
  return raw.normalize('NFKC').replace(INVISIBLE_CHARS, '').replace(MARK_FLOOD, '$1').replace(/\s+/gu, ' ').trim();
}

/** A name typed by a person: sanitized, then 1-32 characters. */
export const PlayerNameInputSchema = z
  .string()
  .max(PROTOCOL_LIMITS.playerNameInputMaxLength)
  .transform(sanitizePlayerName)
  .pipe(PlayerNameSchema);

// --- client -> server payloads ------------------------------------------------------

export const CreateRoomPayloadSchema = z.strictObject({ name: PlayerNameInputSchema });
export type CreateRoomPayload = z.input<typeof CreateRoomPayloadSchema>;

export const JoinRoomPayloadSchema = z.strictObject({ code: RoomCodeSchema, name: PlayerNameInputSchema });
export type JoinRoomPayload = z.input<typeof JoinRoomPayloadSchema>;

/** "Jogar contra bots": creates a room with `bots` bots and starts at once. */
export const QuickPlayPayloadSchema = z.strictObject({
  name: PlayerNameInputSchema,
  bots: z.number().int().min(1).max(PROTOCOL_LIMITS.maxBotsPerRequest),
});
export type QuickPlayPayload = z.input<typeof QuickPlayPayloadSchema>;

export const ResumeSessionPayloadSchema = z.strictObject({ token: SessionTokenSchema });
export type ResumeSessionPayload = z.input<typeof ResumeSessionPayloadSchema>;

export const RemoveBotPayloadSchema = z.strictObject({ playerId: PlayerIdSchema });
export type RemoveBotPayload = z.input<typeof RemoveBotPayloadSchema>;

/**
 * "Configurações da mesa": the host sets them in the lobby (or between games)
 * before starting. They become the rules of the next game of the room.
 * `powers` lists the ranks whose power is on (a rank with no power in the
 * server rules is refused).
 */
export const TableSettingsSchema = z.strictObject({
  turnSeconds: z.number().int().min(PROTOCOL_LIMITS.tableTurnSecondsMin).max(PROTOCOL_LIMITS.tableTurnSecondsMax),
  reactions: z.strictObject({ matchOwn: z.boolean(), matchOpponent: z.boolean() }),
  powers: z
    .array(z.enum(RANKS))
    .max(RANKS.length)
    .refine((ranks) => new Set(ranks).size === ranks.length, 'powers must not repeat'),
});
export type SetTableSettingsPayload = z.input<typeof TableSettingsSchema>;

/** Events without data take `{}` (or nothing). */
export const EmptyPayloadSchema = z.strictObject({}).optional();
export type EmptyPayload = Record<string, never>;

/** `game:action` carries one engine action as is (see actions.ts). */
export const GameActionPayloadSchema = ActionSchema;

// --- server -> client data -------------------------------------------------------------

/** lobby: waiting to start; playing: a game is running; ended: the last game finished (can start again). */
export type RoomStatus = 'lobby' | 'playing' | 'ended';

export interface RoomMemberView {
  readonly id: PlayerId;
  readonly name: string;
  readonly isBot: boolean;
  readonly isHost: boolean;
  /** Bots are always connected. A human who dropped (did not leave) during a game stays seated as disconnected. A human who leaves is replaced by a bot (isBot becomes true, same id). */
  readonly connected: boolean;
}

/** Table settings as the room currently has them. */
export interface TableSettingsView {
  /** Time per decision of the turn, in seconds (default 15). */
  readonly turnSeconds: number;
  /** "Filha da putinha" (matchOwn) and "filho da puta" (matchOpponent), each on or off. */
  readonly reactions: { readonly matchOwn: boolean; readonly matchOpponent: boolean };
  /** Ranks whose power is on, in rank order. */
  readonly powers: readonly Rank[];
}

/** Someone waiting for the next game (joined while a game was running). */
export interface QueuedMemberView {
  readonly id: PlayerId;
  readonly name: string;
  readonly connected: boolean;
}

export interface RoomSettingsView {
  readonly minPlayers: number;
  readonly maxPlayers: number;
  /** Time the current player has for each decision of the turn (draw, keep/discard, power). */
  readonly turnMs: number;
}

/** Public room information. `you` differs per recipient; everything else is the same for everyone. */
export interface RoomView {
  readonly code: string;
  readonly status: RoomStatus;
  readonly you: PlayerId;
  readonly hostId: PlayerId;
  /** In seat order (the order of the next game). */
  readonly members: readonly RoomMemberView[];
  readonly settings: RoomSettingsView;
  /** Current table settings (the next game uses them). */
  readonly table: TableSettingsView;
  /** Every rank that has a power in the server rules, whether or not it is on at this table (`table.powers` is the subset on). */
  readonly availablePowers: readonly Rank[];
  /** Waiting for the next game, in arrival order. They are not in `members` and see the game as spectators. */
  readonly queue: readonly QueuedMemberView[];
}

/** Server notices mixed into the event stream (not produced by the engine). */
export type ServerNotice = {
  readonly type: 'turnTimedOut';
  readonly playerId: PlayerId;
  readonly turnNumber: number;
  /** The step that ran out of time; the server then plays the rest of that turn minimally. */
  readonly step: TurnStep;
};

export type ServerGameEvent = GameEvent | ServerNotice;

/** Sent to each player separately. `view` is built for the recipient only. */
export interface GameUpdate {
  readonly view: GameView;
  /** When the server plays for the current player if they do not act; null when not waiting for them. */
  readonly turnDeadline: number | null;
  /** Public events since the previous update (empty in a snapshot after joining or reconnecting). */
  readonly events: readonly ServerGameEvent[];
}

/** idle: no activity for too long; empty: no human left or connected; shutdown: server stopping; error: unexpected failure. */
export type RoomClosedReason = 'idle' | 'empty' | 'shutdown' | 'error';

export interface RoomClosed {
  readonly code: string;
  readonly reason: RoomClosedReason;
}

/** Ack of room:create, room:join and room:quickPlay. Keep the token secret; it is the only way back in. */
export interface JoinedRoom {
  readonly playerId: PlayerId;
  readonly token: string;
  readonly room: RoomView;
}

/** Ack of session:resume. */
export interface ResumedSession {
  readonly playerId: PlayerId;
  readonly room: RoomView;
}

// --- errors -------------------------------------------------------------------------------

export const PROTOCOL_ERROR_CODES = [
  /** Payload missing, malformed, or failing its schema. */
  'BAD_REQUEST',
  /** Event name not part of the protocol. */
  'UNKNOWN_EVENT',
  /** Too many messages; slow down. */
  'RATE_LIMITED',
  /** Unexpected server failure. No detail is ever sent. */
  'INTERNAL_ERROR',
  /** The session token is unknown or expired (room closed or player left). */
  'INVALID_SESSION',
  /** The connection is not in a room. */
  'NOT_IN_ROOM',
  /** The connection is already in a room (leave it first). */
  'ALREADY_IN_ROOM',
  'ROOM_NOT_FOUND',
  /** No seat left, or the waiting queue is full (or too many bots requested). */
  'ROOM_FULL',
  /** No longer returned by room:join (players who arrive mid-game are queued); kept for compatibility. */
  'ROOM_IN_GAME',
  /** Room limit reached (for the whole server or for this address). */
  'ROOM_LIMIT',
  /** Only the host can do this. */
  'NOT_HOST',
  /** Not enough players to start. */
  'NOT_ENOUGH_PLAYERS',
  /** The player to remove is not a bot of this room. */
  'NOT_A_BOT',
  /** No game in this room. */
  'NO_GAME',
  /** Not allowed while a game is running (start, add/remove bot, room:setTable). */
  'GAME_IN_PROGRESS',
] as const;

export type ProtocolErrorCode = (typeof PROTOCOL_ERROR_CODES)[number];

/** Engine codes (errors.ts) are returned as is for refused game actions. */
export type ServerErrorCode = ProtocolErrorCode | ErrorCode;

export interface ProtocolError {
  readonly code: ServerErrorCode;
  /** Short generic text (English) for developers. The client shows its own message for the code. */
  readonly message: string;
}

export type Ack<T> = { readonly ok: true; readonly data: T } | { readonly ok: false; readonly error: ProtocolError };

/** Connection refusals arrive as `connect_error` with one of these messages. */
export const CONNECTION_ERROR_MESSAGES = ['SERVER_FULL', 'TOO_MANY_CONNECTIONS'] as const;
export type ConnectionErrorMessage = (typeof CONNECTION_ERROR_MESSAGES)[number];

// --- event maps (typed Socket.IO) -------------------------------------------------------

type AckFn<T> = (response: Ack<T>) => void;

/** Client -> server. Always pass the ack callback: it is the only reply. */
export interface ClientToServerEvents {
  'room:create': (payload: CreateRoomPayload, ack: AckFn<JoinedRoom>) => void;
  'room:join': (payload: JoinRoomPayload, ack: AckFn<JoinedRoom>) => void;
  'room:quickPlay': (payload: QuickPlayPayload, ack: AckFn<JoinedRoom>) => void;
  'session:resume': (payload: ResumeSessionPayload, ack: AckFn<ResumedSession>) => void;
  'room:leave': (payload: EmptyPayload, ack: AckFn<null>) => void;
  'room:addBot': (payload: EmptyPayload, ack: AckFn<null>) => void;
  'room:removeBot': (payload: RemoveBotPayload, ack: AckFn<null>) => void;
  'room:start': (payload: EmptyPayload, ack: AckFn<null>) => void;
  'room:setTable': (payload: SetTableSettingsPayload, ack: AckFn<null>) => void;
  'game:action': (payload: Action, ack: AckFn<null>) => void;
}

export type ClientEventName = keyof ClientToServerEvents;

export const CLIENT_EVENT_NAMES = [
  'room:create',
  'room:join',
  'room:quickPlay',
  'session:resume',
  'room:leave',
  'room:addBot',
  'room:removeBot',
  'room:start',
  'room:setTable',
  'game:action',
] as const satisfies readonly ClientEventName[];

/** Server -> client pushes. */
export interface ServerToClientEvents {
  'room:state': (room: RoomView) => void;
  'game:update': (update: GameUpdate) => void;
  'room:closed': (info: RoomClosed) => void;
  /** Another connection resumed this session; this one is no longer bound to the player. */
  'session:replaced': () => void;
}
