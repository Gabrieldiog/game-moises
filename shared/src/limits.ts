// Protocol limits: sanity bounds for anything a client can send.
// These are NOT game rules (those live in server/src/config/rules.ts). The
// server always validates again against the real game state; these bounds only
// stop absurd payloads before they reach the engine.
export const PROTOCOL_LIMITS = {
  playerIdMinLength: 1,
  playerIdMaxLength: 64,
  playerNameMinLength: 1,
  playerNameMaxLength: 32,
  /** Raw name length accepted before sanitizing (sanitizing may shorten it). */
  playerNameInputMaxLength: 128,
  /** Highest slot index accepted in a message. Grids never grow beyond the
   * initial deal (the server config caps it at 16 slots). */
  maxSlotIndex: 15,
  /** Most targets a single power message may name. */
  maxPowerTargets: 8,
  /** Table settings: time per decision, in seconds. */
  tableTurnSecondsMin: 5,
  tableTurnSecondsMax: 60,
  /** Most bots a single quick-play request may ask for (the rules cap it further). */
  maxBotsPerRequest: 15,
} as const;

/** Allowed characters for player ids (generated by the server). */
export const PLAYER_ID_PATTERN = /^[A-Za-z0-9_-]+$/;
